#!/usr/bin/env python3
"""Embed the original Blish HUD events.json as a deterministic C++ schedule.

Only standard-library Python is required. Duplicate name/category rows merge
their starts while retaining the first row's metadata, as in Meta.Load.
"""
import argparse
import json
from pathlib import Path
import re

DAY = 86400
TEXT_FIELDS = ("name", "colloquial", "category", "location", "difficulty", "waypoint", "wiki", "icon")


def parse_interval(value):
    if value in (None, ""):
        return None
    match = re.fullmatch(r"(?:(\d+)\.)?(\d{1,2}):(\d{2})", value)
    if not match:
        raise ValueError(f"Invalid repeat interval: {value!r}")
    days, hours, minutes = (int(part or 0) for part in match.groups())
    if hours >= 24 or minutes >= 60:
        raise ValueError(f"Invalid repeat interval: {value!r}")
    seconds = days * DAY + hours * 3600 + minutes * 60
    if seconds <= 0:
        raise ValueError("Repeat interval must be positive")
    if DAY % seconds:
        raise ValueError("Repeat interval must divide one UTC day")
    return seconds


def parse_offset(value):
    match = re.fullmatch(r"(\d{2}):(\d{2})Z", value)
    if not match:
        raise ValueError(f"Invalid UTC offset: {value!r}")
    hours, minutes = map(int, match.groups())
    if hours >= 24 or minutes >= 60:
        raise ValueError(f"Invalid UTC offset: {value!r}")
    return hours * 3600 + minutes * 60


def optional_minutes(value):
    if value in (None, ""):
        return -1
    if isinstance(value, bool) or int(value) != float(value) or int(value) < 0:
        raise ValueError(f"Invalid minute count: {value!r}")
    return int(value)


def compile_events(rows):
    merged = {}
    for row in rows:
        if not row.get("name") or not row.get("category"):
            raise ValueError("Every event needs a name and category")
        key = (row["name"], row["category"])
        if key not in merged:
            item = {field: row.get(field, "") or "" for field in TEXT_FIELDS}
            item.update(duration_minutes=optional_minutes(row.get("duration")),
                        alert_minutes=optional_minutes(row.get("alert")), starts=set())
            merged[key] = item
        offset = parse_offset(row["offset"])
        repeat = parse_interval(row.get("repeat"))
        starts = {offset} if repeat is None else {
            (offset + step) % DAY for step in range(0, DAY, repeat)
        }
        merged[key]["starts"].update(starts)
    return [{**item, "starts": sorted(item["starts"])} for item in merged.values()]


def cpp_string(value):
    # UTF-8 source literals; JSON quoting handles control characters and quotes.
    return json.dumps(value, ensure_ascii=False)


def render(rows):
    events = compile_events(rows)
    lines = ["// Generated by tools/generate_events.py; edit assets/events.json, then regenerate.",
             "#pragma once", '#include "../src/schedule.hpp"', "", "namespace events {",
             "inline std::vector<Event> bundled_events() {", "    return {"]
    for event in events:
        metadata = ", ".join(cpp_string(event[field]) for field in TEXT_FIELDS)
        starts = ", ".join(map(str, event["starts"]))
        lines.append(f"        {{{metadata}, {event['duration_minutes']}, {event['alert_minutes']}, {{{starts}}}}},")
    lines += ["    };", "}", "} // namespace events", ""]
    return "\n".join(lines)


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", nargs="?", type=Path, default=root / "assets/events.json")
    parser.add_argument("output", nargs="?", type=Path, default=root / "generated/events.hpp")
    parser.add_argument("--check", action="store_true", help="Fail if output differs; do not write")
    args = parser.parse_args()
    rendered = render(json.loads(args.input.read_text(encoding="utf-8-sig")))
    if args.check:
        if args.output.read_text(encoding="utf-8") != rendered:
            parser.exit(1, "Generated events.hpp is stale\n")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(rendered, encoding="utf-8")


if __name__ == "__main__":
    main()
