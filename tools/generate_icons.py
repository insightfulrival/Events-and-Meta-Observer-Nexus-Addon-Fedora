#!/usr/bin/env python3
"""Embed the bundled ArenaNet PNG snapshots; builds require no icon downloads."""
import json
from pathlib import Path


def render(root):
    manifest = json.loads((root / 'assets/icons/manifest.json').read_text())
    keys = {event.get('icon') for event in json.loads((root / 'assets/events.json').read_text()) if event.get('icon')}
    if set(manifest) != keys:
        raise ValueError('Icon manifest must cover exactly the event icon keys')
    lines = ['// Generated by tools/generate_icons.py; do not edit.', '#pragma once',
             '#include <cstddef>', 'namespace bundled_icons {',
             'struct Icon { const char* key; const char* identifier; unsigned char* data; std::size_t size; };']
    entries = []
    for index, (key, name) in enumerate(sorted(manifest.items())):
        if Path(name).name != name:
            raise ValueError('Icon paths must be plain filenames')
        data = (root / 'assets/icons' / name).read_bytes()
        if data[:8] != b'\x89PNG\r\n\x1a\n':
            raise ValueError(f'Not a PNG: {name}')
        lines.append(f'inline unsigned char image_{index}[] = {{')
        for offset in range(0, len(data), 32):
            lines.append('    ' + ','.join(str(byte) for byte in data[offset:offset + 32]) + ',')
        lines.append('};')
        entries.append(f'    {{{json.dumps(key)}, "EVOBS_BUNDLED_{Path(name).stem}", image_{index}, sizeof(image_{index})}},')
    lines += ['inline Icon images[] = {', *entries, '};', '} // namespace bundled_icons', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[1]
    (root / 'generated/icons.hpp').write_text(render(root))
